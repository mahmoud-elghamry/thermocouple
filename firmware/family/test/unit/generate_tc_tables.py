"""Offline NIST ITS-90 tables and reference vectors. No floating point in firmware.

Source: NIST Monograph 175, Appendix A, tables A4 (J), A6 (K), SRD 60.
https://doi.org/10.6028/NIST.MONO.175
Coefficients give mV, temperature in C. K >=0 includes its exponential term.
Run --check to compare committed data and sweep the interpolation error at .05 C.
"""
import argparse
import bisect
import math
from pathlib import Path

KNEG = [0, .394501280250e-1, .236223735980e-4, -.328589067840e-6,
        -.499048287770e-8, -.675090591730e-10, -.574103274280e-12,
        -.310888728940e-14, -.104516093650e-16, -.198892668780e-19,
        -.163226974860e-22]
KPOS = [-.176004136860e-1, .389212049750e-1, .185587700320e-4,
        -.994575928740e-7, .318409457190e-9, -.560728448890e-12,
        .560750590590e-15, -.320207200030e-18, .971511471520e-22,
        -.121047212750e-25]
JLOW = [0, .503811878150e-1, .304758369300e-4, -.856810657200e-7,
        .132281952950e-9, -.170529583370e-12, .209480906970e-15,
        -.125383953360e-18, .156317256970e-22]
JHIGH = [.296456256810e3, -.149761277860e1, .317871039240e-2,
         -.318476867010e-5, .157208190040e-8, -.306913690560e-12]


def emf(kind, t):
    coeff = (KNEG if t < 0 else KPOS) if kind == 'K' else (JLOW if t <= 760 else JHIGH)
    mv = sum(c * t**i for i, c in enumerate(coeff))
    if kind == 'K' and t >= 0:
        mv += .118597600000 * math.exp(-.118343200000e-3 * (t-126.9686)**2)
    return mv * 1_000_000


def products():
    root = Path(__file__).resolve().parents[2]
    text = '/* Generated by test/unit/generate_tc_tables.py; NIST MONO 175 A4/A6. */\n'
    text += '#include "services/tc_tables.h"\n'
    text += '#ifdef __AVR__\n#include <avr/pgmspace.h>\n#define FLASH PROGMEM\n'
    text += '#else\n#define FLASH\n#endif\n'
    vectors = '/* Independent full-function reference samples, nV rounded to nearest. */\n'
    vectors += 'typedef struct { ch_type_t type; temp_dC_t temp; emf_nV_t emf; } tc_vector_t;\n'
    vectors += 'static const tc_vector_t tc_vectors[]={\n'
    for kind, lo, hi in [('K', -200, 1372), ('J', -210, 1200)]:
        temps = list(range(lo, hi+1, 10))
        if temps[-1] != hi:
            temps.append(hi)
        values = [round(emf(kind, t)) for t in temps]
        assert all(a < b for a, b in zip(values, values[1:]))
        text += f'static const int32_t table_{kind}[{len(values)}] FLASH={{\n'
        for i in range(0, len(values), 6):
            text += '    ' + ', '.join(str(v)+'L' for v in values[i:i+6])+',\n'
        text += '};\n'
        refs = sorted(set([lo, hi, -195 if kind == 'K' else -205, 760] + list(range(-200, hi, 50))))
        for t in refs:
            if lo <= t <= hi:
                vectors += f'    {{CH_TYPE_{kind}, {t*10}, {round(emf(kind,t))}L}},\n'
        worst = 0
        operating = 0
        rounded = 0
        for i in range(lo*20, hi*20+1):
            t = i/20
            e = emf(kind, t)
            idx = max(0, min(len(values)-2, bisect.bisect_right(values, e)-1))
            interp = temps[idx]+(e-values[idx])*(temps[idx+1]-temps[idx])/(values[idx+1]-values[idx])
            error = abs(t-interp)
            worst = max(worst,error)
            if t >= -50:
                operating = max(operating,error)
                rounded = max(rounded,abs(t-round(interp*10)/10))
        assert worst <= (.14 if kind == 'K' else .17), (kind,worst)
        assert operating <= .03, (kind,operating)
        print(f'{kind}: {len(values)} entries; interpolation max {worst:.6f} C; >=-50 C {operating:.6f} C; with 0.1 C rounding {rounded:.6f} C')
    text += '''uint16_t tc_table_count(ch_type_t t)
{ return t==CH_TYPE_K?159u:(t==CH_TYPE_J?142u:0u); }
temp_dC_t tc_table_temp(ch_type_t t, uint16_t i)
{
    if(i>=tc_table_count(t)) return TEMP_DC_INVALID;
    if(t==CH_TYPE_K && i==158u) return 13720;
    return (temp_dC_t)((t==CH_TYPE_K?-2000L:-2100L)+100L*i);
}
emf_nV_t tc_table_emf(ch_type_t t, uint16_t i)
{
    if(i>=tc_table_count(t)) return 0;
#ifdef __AVR__
    return (int32_t)pgm_read_dword(t==CH_TYPE_K?&table_K[i]:&table_J[i]);
#else
    return t==CH_TYPE_K?table_K[i]:table_J[i];
#endif
}
'''
    vectors += '};\n'
    return {root/'src/services/tc_tables.c':text,
            root/'test/unit/tc_reference.h':vectors}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    # Published NIST rounded points, separate from interpolation reference generation.
    for kind,t,mv in [('K',100,4.096),('K',1000,41.276),('K',1372,54.886),
                      ('J',100,5.269),('J',760,42.919),('J',1200,69.553)]:
        assert abs(emf(kind,t)/1e6-mv) <= .0005
    for path, content in products().items():
        if args.check:
            assert path.read_text(encoding='utf-8') == content, str(path)
        else:
            path.write_text(content,encoding='utf-8',newline='\n')


if __name__ == '__main__':
    main()
